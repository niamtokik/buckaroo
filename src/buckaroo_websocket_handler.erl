-module(buckaroo_websocket_handler).
-export([init/2]).
-export([websocket_init/1, websocket_handle/2, websocket_info/2]).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
init(Req, State) ->
  WebSocketOpts = #{},
  {cowboy_websocket, Req, State, WebSocketOpts}.

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
websocket_init(State) ->
  {[{text, <<"hey">>}], State}.

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
websocket_handle({text, Message}, State) ->
  {[{text, Message}], State};
websocket_handle(Msg, State) ->
  io:format("handle: ~p~n", [Msg]),
  {[{text, Msg}], State}.

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
websocket_info(Msg, State) ->
  io:format("info: ~p~n", [Msg]),
  {ok, State}.
