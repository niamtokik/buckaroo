-module(buckaroo_cowboy).
-export([start_link/0, stop/0]).
-export([start_quic/0]).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
start_link() ->
  cowboy:start_clear(
    name(),
    transport_options(),
    protocol_options()
  ).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
stop() ->
    cowboy:stop_listener(name()).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
start_quic() ->
  application:ensure_all_started(quicer),
  cowboy:start_quic(
    name(),
    #{
      socket_opts => protocol_options() ++ [
        {certfile, "cert.pem"},
        {keyfile, "key.pem"}
      ]
    },
    protocol_options()
  ).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
name() ->
  buckaroo_listener.

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
routes() ->
  [
    {'_', [
      {"/", buckaroo_handler, #{}},
      {"/ws", buckaroo_websocket_handler, #{}}
    ]
  }].

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
dispatch() ->
  cowboy_router:compile(
    routes()
  ).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
transport_options() ->
  [
    {port, 8081}
  ].

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
protocol_options() ->
  #{
    env => #{
      dispatch => dispatch()
    }
  }.

