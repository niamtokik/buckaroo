-module(buckaroo_cowboy).
-export([start_link/0, stop/0]).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
name() ->
  buckaroo_listener.

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
routes() ->
  [
    {'_', [
      {"/", buckaroo_handler, #{}}
    ]
  }].

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
dispatch() ->
  cowboy_router:compile(
    routes()
  ).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
transport_options() ->
  [
    {port, 8081}
  ].

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
protocol_options() ->
  #{
    env => #{
      dispatch => dispatch()
    }
  }.

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
start_link() ->
  cowboy:start_clear(
    name(),
    transport_options(),
    protocol_options()
  ).

stop() ->
    cowboy:stop_listener(name()).
