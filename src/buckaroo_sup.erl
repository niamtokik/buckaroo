-module(buckaroo_sup).
-behavior(supervisor).
-export([start_link/0, init/1]).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
start_link() ->
  supervisor:start_link({local, ?MODULE}, ?MODULE, []).

%%--------------------------------------------------------------------
%% @doc
%% @end
%%--------------------------------------------------------------------
init(_) ->
  {ok, {supervisor_flags(), child_specs()}}.

%%--------------------------------------------------------------------
%% @hidden
%% @doc
%% @end
%%--------------------------------------------------------------------
supervisor_flags() ->
  #{
    strategy => one_for_all,
    intensity => 0,
    period => 1
  }.

%%--------------------------------------------------------------------
%% @hidden
%% @doc
%% @end
%%--------------------------------------------------------------------
child_specs() ->
  [
    #{
      id => buckaroo_cowboy,
      start => {buckaroo_cowboy, start_link, []}
    }
  ].
